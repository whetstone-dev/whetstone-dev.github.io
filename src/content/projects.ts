import type { Locale } from '@/i18n/config';

type Localized<T> = Record<Locale, T>;

export type ProjectKind = 'skill' | 'guide' | 'site';
export type ProjectStatus = 'active' | 'in-progress';

export interface Project {
  /** Repository name and URL segment: /projects/<slug>/ */
  slug: string;
  kind: ProjectKind;
  status: ProjectStatus;
  /** Kept in sync by hand with the project's latest release */
  version?: string;
  license: string;
  /** Runtime requirement, if any */
  requires?: string;
  /** Number of npm dependencies the project needs at runtime */
  dependencies?: number;
  repo: string;
  /** The project's own website, if it has one */
  site?: string;
  /** One sentence for cards */
  summary: Localized<string>;
  /** Longer description for the detail page */
  description: Localized<string>;
  preview: { src: string; width: number; height: number; alt: Localized<string> };
  /** Skills only: how to install it */
  install?: { npx: string; git: { unix: string; windows: string } };
  /** Skills only: example requests that show what it is good at */
  prompts?: Localized<string[]>;
  /** Real outputs published on the project's site, shown live on its detail page */
  artifacts?: { base: string; items: { file: string; label: Localized<string>; note: Localized<string> }[] };
}

